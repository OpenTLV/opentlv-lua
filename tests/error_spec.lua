local opentlv = require("opentlv")

describe("opentlv.errors", function()
    it("mirrors every tlv_result_t code", function()
        assert(opentlv.errors.OK == 0)
        assert(opentlv.errors.END == 1)
        assert(opentlv.errors.NEED_MORE_DATA == 2)
        assert(opentlv.errors.TRUNCATED == 3)
        assert(opentlv.errors.INVALID_TAG == 4)
        assert(opentlv.errors.INVALID_TAG_SIZE == 5)
        assert(opentlv.errors.INVALID_LENGTH == 6)
        assert(opentlv.errors.INVALID_VALUE == 7)
        assert(opentlv.errors.SYNTAX == 8)
        assert(opentlv.errors.SCHEMA == 9)
        assert(opentlv.errors.NULL_ARG == 10)
        assert(opentlv.errors.INVALID_ARG == 11)
        assert(opentlv.errors.INVALID_STATE == 12)
        assert(opentlv.errors.INVALID_SCHEMA == 13)
        assert(opentlv.errors.BUFFER_TOO_SHORT == 14)
        assert(opentlv.errors.LIMIT == 15)
        assert(opentlv.errors.OVERFLOW == 16)
        assert(opentlv.errors.NATIVE_SIZE == 17)
        assert(opentlv.errors.OUT_OF_MEMORY == 18)
        assert(opentlv.errors.UNSUPPORTED == 19)
        assert(opentlv.errors.VISITOR == 20)
        assert(opentlv.errors.CALLBACK == 21)
    end)
end)

describe("opentlv.strerror", function()
    it("describes a known code as a non-empty string", function()
        local message = opentlv.strerror(opentlv.errors.BUFFER_TOO_SHORT)
        assert(type(message) == "string")
        assert(#message > 0)
    end)

    it("describes an unrecognized code without raising", function()
        local message = opentlv.strerror(9999)
        assert(type(message) == "string")
    end)
end)

describe("opentlv.version", function()
    it("returns a non-empty string, also available as opentlv._VERSION", function()
        assert(type(opentlv.version()) == "string")
        assert(#opentlv.version() > 0)
        assert(opentlv._VERSION == opentlv.version())
    end)
end)

describe("error objects", function()
    it("format as a readable string via tostring()", function()
        local ok, err = pcall(function()
            for _ in opentlv.reader(string.char(0x01), opentlv.formats.ber) do
            end
        end)
        assert(not ok)
        local text = tostring(err)
        assert(text:find("opentlv:", 1, true) ~= nil)
        assert(text:find(tostring(err.code), 1, true) ~= nil)
    end)

    it("carry a message describing the code", function()
        local ok, err = pcall(function()
            for _ in opentlv.reader(string.char(0x01), opentlv.formats.ber) do
            end
        end)
        assert(not ok)
        assert(err.message == opentlv.strerror(err.code))
        assert(err.severity == "error")
    end)
end)
